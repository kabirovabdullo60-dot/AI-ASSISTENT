/// Which of the assistant's languages ('en' / 'ru' / 'tg') a message is written in, so the
/// assistant answers in the language the owner wrote, whatever the site's language is.
/// Tajik may be typed in Cyrillic or in Latin letters ("yak magazini nav ilova kun").
/// Returns null when the message is too short or too mixed to tell (e.g. "ok", "100").
String? detectMessageLanguage(String text) {
  final t = text.toLowerCase();
  if (RegExp('[ӣӯҳҷқғ]').hasMatch(t)) return 'tg';
  final words = RegExp(r'[a-zа-яё]+', unicode: true).allMatches(t).map((m) => m.group(0)!).toList();
  if (words.isEmpty) return null;

  final cyrillic = words.where((w) => RegExp('[а-яё]').hasMatch(w)).toList();
  final latin = words.where((w) => RegExp('[a-z]').hasMatch(w)).toList();

  if (cyrillic.length >= latin.length) {
    // Tajik typed without its special letters still uses its own everyday words.
    final tg = cyrillic.where(_tajikCyrillic.contains).length;
    return tg >= 1 && tg * 4 >= cyrillic.length ? 'tg' : 'ru';
  }
  final tg = latin.where((w) => _tajikLatin.contains(w) || _tajikLatinStems.any(w.startsWith)).length;
  final en = latin.where(_english.contains).length;
  if (tg >= 2 || (tg >= 1 && tg > en)) return 'tg';
  if (en >= 1 || latin.length >= 3) return 'en';
  return null;
}

